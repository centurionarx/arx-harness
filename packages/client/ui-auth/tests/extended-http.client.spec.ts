// @vitest-environment jsdom
/** UI workflows use the real issuer, owner storage, cookies and CSRF; only email delivery is fake. */
import { beforeEach, afterEach, describe, expect, it, vi } from 'vitest'
import { act, fireEvent, screen, waitFor, within } from '@testing-library/react'
import { AUTH_HEADER, parseAuthState, parseAdminUserList, parseModuleCatalog } from '@arx-ai/arx-web-identity/contract'
import { applicationFixture } from './composition.client.ts'
import { browserFixture, httpBridge } from './http-fixture.client.ts'
const dispose: Array<() => void | Promise<void>> = []
let prepared: Awaited<ReturnType<typeof browserFixture>>
beforeEach(async () => {
  prepared = await browserFixture((expect.getState().currentTestName ?? '').includes('MASTER UI') ? 'admin' : 'user')
})
afterEach(async () => {
  for (const close of dispose.splice(0).reverse()) await close()
  await prepared.close()
  vi.restoreAllMocks(); vi.unstubAllGlobals(); localStorage.clear(); sessionStorage.clear()
  history.replaceState(null, '', '/'); document.body.replaceChildren()
})
function services(audience: 'user' | 'admin' = 'user') {
  expect(prepared.audience).toBe(audience)
  return Promise.resolve(prepared)
}
async function enter(bridge: ReturnType<typeof httpBridge>, identifier: string, password: string) {
  const response = await bridge.fetcher('/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json', [AUTH_HEADER]: '1' },
    body: JSON.stringify({ identifier, password }) })
  expect(response.ok).toBe(true); return parseAuthState(await response.json())
}
async function mount() {
  const ui = await applicationFixture(); dispose.push(() => ui.close()); return ui
}
describe('native UI mutations and recovery with real HTTP', () => {
  it('refreshes invitations, corrected recipients, module grants, blocking and logical deletion from MASTER UI', async () => {
    const fixture = await services('admin'), bridge = httpBridge(fixture.url)
    await enter(bridge, 'arxadmin', fixture.masterPassword); bridge.install()
    const ui = await mount()
    await screen.findByText('fixture-user-0')
    fireEvent.change(screen.getByLabelText('Nome de usuário'), { target: { value: 'ui-workflow' } })
    fireEvent.change(screen.getByLabelText('E-mail'), { target: { value: 'ui-workflow@fixture.test' } })
    fireEvent.click(screen.getByRole('button', { name: 'Criar usuário' }))
    const row = (await screen.findByText('ui-workflow')).closest('li')!
    expect(within(row).getByText('Estado: Pendente')).toBeTruthy()
    fireEvent.click(within(row).getByRole('button', { name: 'Corrigir e-mail do convite' }))
    fireEvent.change(within(row).getByLabelText('E-mail'), { target: { value: 'ui-corrected@fixture.test' } })
    fireEvent.click(within(row).getByRole('button', { name: 'Salvar' }))
    await within(row).findByText('ui-corrected@fixture.test')
    fireEvent.click(within(row).getByRole('button', { name: 'Enviar convite' }))
    await waitFor(() => { expect(screen.getByRole('status').textContent).toBe('Operação concluída.') })
    const link = await fixture.command('recovery-link', { purpose: 'invitation', to: 'ui-corrected@fixture.test' })
    expect(new URL(String(link.link)).hash.startsWith('#invite=')).toBe(true)
    fireEvent.click(within(row).getByRole('button', { name: 'Liberar acesso' }))
    await within(row).findByText('Estado: Ativo')
    const users = parseAdminUserList(await (await bridge.fetcher('/admin/users')).json())
    const selected = users.users.find(user => user.username === 'ui-workflow')!
    fireEvent.click(screen.getByRole('button', { name: 'Módulos' }))
    fireEvent.change(screen.getByLabelText('Selecione um usuário'), { target: { value: selected.userId } })
    const modules = parseModuleCatalog(await (await bridge.fetcher('/admin/modules')).json())
    const item = modules.modules[0]!
    const checkbox = screen.getByLabelText(item.label)
    fireEvent.click(checkbox)
    await waitFor(() => { expect((checkbox as HTMLInputElement).checked).toBe(true) })
    fireEvent.click(checkbox)
    await waitFor(() => { expect((checkbox as HTMLInputElement).checked).toBe(false) })
    fireEvent.click(screen.getByRole('button', { name: 'Usuários' }))
    const activeRow = screen.getByText('ui-workflow').closest('li')!
    fireEvent.click(within(activeRow).getByRole('button', { name: 'Bloquear acesso' }))
    await within(activeRow).findByText('Estado: Bloqueado')
    fireEvent.click(screen.getByRole('button', { name: 'Atualizar' }))
    await waitFor(() => { expect(within(activeRow).getByText('Estado: Bloqueado')).toBeTruthy() })
    await waitFor(() => { expect(within(activeRow).getByRole('button', { name: 'Excluir acesso' }).hasAttribute('disabled')).toBe(false) })
    fireEvent.click(within(activeRow).getByRole('button', { name: 'Excluir acesso' }))
    expect(within(activeRow).getByRole('button', { name: 'Confirmar exclusão do acesso' })).toBeTruthy()
    fireEvent.click(within(activeRow).getByRole('button', { name: 'Confirmar exclusão do acesso' }))
    await within(activeRow).findByText('Estado: Excluído')
    expect(within(activeRow).queryByRole('button')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Minha conta' }))
    expect(screen.getByText('admin@centurionarx.com')).toBeTruthy()
    expect(screen.getByText('Nenhum módulo liberado.')).toBeTruthy()
    fireEvent.click(screen.getAllByRole('button', { name: 'Sair' })[0]!)
    await waitFor(() => { expect(ui.reloads).toEqual(['reload']) })
    expect(ui.container.textContent).toBe('')
    expect(bridge.requests.some(request => request.path.startsWith('/user/') || request.path.startsWith('/api/'))).toBe(false)
  })
  it('creates only virtual owner resources, traps history focus and refetches after rename, delete and ungroup', async () => {
    const fixture = await services()
    await fixture.command('set-modules', { index: 0, grants: ['storage'] })
    const seed = await fixture.command('seed-history', { index: 0 })
    const bridge = httpBridge(fixture.url); await enter(bridge, fixture.users[0]!.username, fixture.users[0]!.password); bridge.install()
    const ui = await mount()
    const projects = await screen.findByRole('combobox', { name: 'Meus projetos' })
    await waitFor(() => { expect(within(projects).getByRole('option', { name: 'Projeto privado 0' })).toBeTruthy() })
    fireEvent.change(projects, { target: { value: seed.projectId } })
    await screen.findByText('Conversa privada 0')
    const historyButton = screen.getByRole('button', { name: 'Ver histórico' }); historyButton.focus(); fireEvent.click(historyButton)
    const dialog = await screen.findByRole('dialog')
    await waitFor(() => { expect(dialog.querySelector('pre')?.textContent).toContain('Registro próprio 0') })
    const close = within(dialog).getByRole('button', { name: 'Fechar' })
    expect(document.activeElement).toBe(close)
    fireEvent.keyDown(close, { key: 'Tab', shiftKey: true }); expect(document.activeElement).toBe(close)
    fireEvent.keyDown(close, { key: 'Tab' }); expect(document.activeElement).toBe(close)
    fireEvent.keyDown(close, { key: 'ArrowDown' })
    fireEvent.keyDown(close, { key: 'Escape' })
    expect(screen.queryByRole('dialog')).toBeNull(); expect(document.activeElement).toBe(historyButton)
    fireEvent.click(screen.getByRole('button', { name: 'Renomear conversa' }))
    fireEvent.change(screen.getByLabelText('Renomear conversa'), { target: { value: 'Título próprio novo' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salvar' }))
    await screen.findByText('Título próprio novo')
    fireEvent.click(screen.getByRole('button', { name: 'Excluir conversa' }))
    expect(screen.getByText('A exclusão remove esta conversa. Os arquivos do projeto são preservados.')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Confirmar exclusão da conversa' }))
    await screen.findByText('Nenhuma sessão salva neste projeto.')
    fireEvent.click(screen.getByRole('button', { name: 'Remover agrupamento' }))
    await screen.findByText('Nenhum workspace neste projeto.')
    fireEvent.change(projects, { target: { value: '' } })
    await waitFor(() => { expect(screen.queryByText('Workspaces próprios')).toBeNull() })
    await waitFor(() => { expect(screen.getByRole('button', { name: 'Criar projeto' }).hasAttribute('disabled')).toBe(false) })
    fireEvent.change(screen.getByLabelText('Nome do projeto'), { target: { value: 'Outro projeto próprio' } })
    fireEvent.click(screen.getByRole('button', { name: 'Criar projeto' }))
    await screen.findByRole('option', { name: 'Outro projeto próprio' })
    await waitFor(() => { expect(screen.getByRole('button', { name: 'Criar workspace' }).hasAttribute('disabled')).toBe(false) })
    fireEvent.change(screen.getByLabelText('Nome do workspace'), { target: { value: 'Nome virtual' } })
    fireEvent.click(screen.getByRole('button', { name: 'Criar workspace' }))
    await screen.findByText('Nome virtual')
    expect(screen.getByRole('button', { name: 'Abrir workspace' }).hasAttribute('disabled')).toBe(true)
    fireEvent.click(screen.getByRole('button', { name: 'Minha conta' }))
    const form = ui.container.querySelector('form')!
    fireEvent.change(screen.getByLabelText('Senha atual'), { target: { value: fixture.users[0]!.password } })
    fireEvent.change(screen.getByLabelText('Nova senha'), { target: { value: 'Fixture-' + crypto.randomUUID() } })
    fireEvent.change(screen.getByLabelText('Confirmar nova senha'), { target: { value: 'Different-fixture' } })
    await act(async () => { fireEvent.submit(form) })
    expect(screen.getByRole('alert').textContent).toBe('As senhas precisam ser iguais.')
    expect(screen.getByLabelText<HTMLInputElement>('Senha atual').value).toBe('')
    fireEvent.click(screen.getAllByRole('button', { name: 'Sair' })[0]!)
    await waitFor(() => { expect(ui.reloads).toEqual(['reload']) })
  })
  it('reports real invalid credentials and recovery errors without rendering submitted secrets or server messages', async () => {
    const fixture = await services(), bridge = httpBridge(fixture.url); bridge.install()
    const ui = await mount()
    const wrong = 'Fixture-' + crypto.randomUUID()
    fireEvent.change(screen.getByLabelText('Nome de usuário ou e-mail'), { target: { value: fixture.users[0]!.username } })
    fireEvent.change(screen.getByLabelText('Senha'), { target: { value: wrong } })
    await act(async () => { fireEvent.submit(ui.container.querySelector('form')!) })
    await screen.findByRole('alert')
    expect(ui.container.textContent).not.toContain(wrong)
    expect(screen.getByLabelText<HTMLInputElement>('Senha').value).toBe('')
    fireEvent.click(screen.getByRole('button', { name: 'Esqueci minha senha' }))
    expect(screen.queryByLabelText('Senha')).toBeNull()
    fireEvent.change(screen.getByLabelText('Nome de usuário ou e-mail'), { target: { value: fixture.users[0]!.username } })
    await act(async () => { fireEvent.submit(ui.container.querySelector('form')!) })
    await screen.findByText('Se houver uma conta elegível, você receberá as instruções de recuperação.')
    fireEvent.click(screen.getByRole('button', { name: 'Voltar ao acesso' }))
    expect(ui.reloads).toEqual(['reload']); await ui.close()
    history.replaceState(null, '', '/reset#reset=invalid-fixture-token')
    const recovery = await mount()
    fireEvent.change(screen.getByLabelText('Nova senha'), { target: { value: wrong } })
    fireEvent.change(screen.getByLabelText('Confirmar nova senha'), { target: { value: 'mismatch-fixture' } })
    await act(async () => { fireEvent.submit(recovery.container.querySelector('form')!) })
    expect(screen.getByRole('alert').textContent).toBe('As senhas precisam ser iguais.')
    fireEvent.change(screen.getByLabelText('Nova senha'), { target: { value: wrong } })
    fireEvent.change(screen.getByLabelText('Confirmar nova senha'), { target: { value: wrong } })
    await act(async () => { fireEvent.submit(recovery.container.querySelector('form')!) })
    await waitFor(() => { expect(screen.getByRole('alert').textContent).toBe('Este link expirou ou já foi usado. Solicite um novo link.') })
    expect(location.hash).toBe(''); expect(history.state).toBeNull()
    expect(recovery.container.textContent).not.toContain('invalid-fixture-token')
  })
})
