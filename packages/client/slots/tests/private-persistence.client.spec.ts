// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from 'vitest'
import { createSnapshotStore, defineStore, enterStorePersistence, purgePrivateViewStorage } from '../src/client/store.ts'
afterEach(() => {
  vi.restoreAllMocks(); vi.unstubAllGlobals(); vi.unstubAllEnvs(); localStorage.clear()
  enterStorePersistence(false)
})
describe('private view persistence lifetimes', () => {
  it('purges legacy private keys and prevents old stores or disposers from writing into a new tree', () => {
    const local = enterStorePersistence(false)
    const store = createSnapshotStore({ selection: 'before-login' }, { persist: { name: 'arx.selection' } })
    store.set({ selection: 'old-owner' })
    localStorage.setItem('unrelated.application', 'retained')
    const native = enterStorePersistence(true)
    expect(localStorage.getItem('arx.selection')).toBeNull()
    expect(localStorage.getItem('unrelated.application')).toBe('retained')
    local()
    store.set({ selection: 'stale-callback' })
    expect(localStorage.getItem('arx.selection')).toBeNull()
    const fresh = createSnapshotStore({ selection: 'new-tree' }, { persist: { name: 'arx.selection' } })
    expect(fresh.getSnapshot()).toEqual({ selection: 'new-tree' })
    fresh.set({ selection: 'new-selection' })
    expect(localStorage.getItem('arx.selection')).toBeNull()
    localStorage.setItem('arx.late-cache', 'private')
    native()
    expect(localStorage.getItem('arx.late-cache')).toBeNull()
    expect(localStorage.getItem('unrelated.application')).toBe('retained')
  })
  it('keeps stores usable when real storage rejects parsing, writes, or cleanup', () => {
    enterStorePersistence(false)
    localStorage.setItem('arx.corrupt', '[')
    const report = vi.spyOn(console, 'error').mockImplementation(() => {})
    const store = createSnapshotStore({ value: 1 }, { persist: { name: 'arx.corrupt' } })
    expect(store.getSnapshot()).toEqual({ value: 1 })
    expect(report).toHaveBeenCalledOnce()
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('storage unavailable') })
    store.set({ value: 2 })
    expect(store.getSnapshot()).toEqual({ value: 2 })
    expect(report).toHaveBeenCalledTimes(2)
    vi.spyOn(Storage.prototype, 'removeItem').mockImplementation(() => { throw new Error('storage unavailable') })
    expect(() => { purgePrivateViewStorage() }).not.toThrow()
    const handle = defineStore({ init: () => ({ value: 0 }), persist: 'arx.corrupt', actions: {} })
    expect(() => { handle.create().clearPersisted() }).not.toThrow()
  })
  it('disables persistence in non-browser environments and does not require storage to purge', () => {
    vi.stubGlobal('localStorage', undefined)
    enterStorePersistence(false)
    expect(() => { purgePrivateViewStorage() }).not.toThrow()
    const store = createSnapshotStore('initial', { persist: { name: 'arx.absent' } })
    store.set('usable'); expect(store.getSnapshot()).toBe('usable')
    const handle = defineStore({ init: () => ({ value: 0 }), persist: 'arx.absent', actions: {} })
    expect(() => { handle.create().clearPersisted() }).not.toThrow()
  })
  it('keeps production replacements writable while development snapshots freeze recursively', () => {
    vi.stubEnv('NODE_ENV', 'production')
    const replacement = { nested: { value: 2 } }
    const store = createSnapshotStore({ nested: { value: 1 } })
    store.set(replacement)
    expect(Object.isFrozen(replacement)).toBe(false)
    expect(store.getSnapshot()).toBe(replacement)
    vi.stubEnv('NODE_ENV', 'test')
    const alreadyFrozen = Object.freeze({ value: 3 })
    const next = { nested: alreadyFrozen }
    store.set(next)
    expect(Object.isFrozen(next)).toBe(true)
    expect(Object.isFrozen(alreadyFrozen)).toBe(true)
  })
})
